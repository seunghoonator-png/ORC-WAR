/// 문자열을 찍는다. `scale` 은 글자 확대 배수.
pub fn text(frame: &mut Frame, x: i32, y: i32, s: &str, scale: i32, color: u32) {
    let mut cx = x;
    for ch in s.chars() {
        if let Some(g) = glyph(ch) {
            for (row, bits) in g.iter().enumerate() {
                for col in 0..GLYPH_W {
                    if bits & (1 << (GLYPH_W - 1 - col)) != 0 {
                        frame.blot(
                            cx + col as i32 * scale,
                            y + row as i32 * scale,
                            scale,
                            color,
                        );
                    }
                }
            }
        }
        cx += (GLYPH_W as i32 + 1) * scale;
    }
}

/// 문자열이 차지할 너비(화소).
pub fn width(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * (GLYPH_W as i32 + 1) * scale
}
